/*
 * aes256.h - AES-256 single-block ECB decryption (FIPS 197), used to compute
 * the CBC IV for the IPsec ESP page-cache write primitive (CVE-2026-43284).
 *
 * Primitive semantics (DirtyFrag-style):
 *   The kernel decrypts the target page in place with AES-CBC, so the new
 *   file content at the target offset becomes
 *       new = AES_ECB_DEC(key, old) XOR IV
 *   To land `desired` we therefore send
 *       IV = AES_ECB_DEC(key, old) XOR desired
 *   and the packet's ciphertext block carries the file's old content, which
 *   is exactly the in-place decrypt input.
 *
 * Header-only implementation, plain C, FIPS 197 tables, so it compiles clean
 * under -Werror for both the NDK engine build and host unit tests.
 */
