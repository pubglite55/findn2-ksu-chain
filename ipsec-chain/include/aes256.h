static uint8_t aes_gmul(uint8_t a, uint8_t b)
{
    uint8_t p = 0;
    while (b != 0) {
        if (b & 1)
            p = (uint8_t)(p ^ a);
        a = (uint8_t)((a << 1) ^ ((a & 0x80) ? 0x1b : 0x00));
        b >>= 1;
    }
    return p;
}

static uint32_t aes_subword(uint32_t w)
{
    return ((uint32_t)kAesSbox[(w >> 24) & 0xff] << 24) |
           ((uint32_t)kAesSbox[(w >> 16) & 0xff] << 16) |
           ((uint32_t)kAesSbox[(w >> 8) & 0xff] << 8) |
           (uint32_t)kAesSbox[w & 0xff];
}

/* Expand a 32-byte key into 240 bytes of round-key material (big-endian words). */
static inline void aes256_key_expand(const uint8_t key[AES256_KEY_SZ],
                                     uint8_t rk[AES256_RK_BYTES])
{
    /* rcon index used is i/8 for i in {8,16,...,56} -> 1..7 */
    static const uint8_t rcon[8] = {0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40};
    uint32_t w[AES256_RK_WORDS];
    int i;

    for (i = 0; i < 8; i++) {
        w[i] = ((uint32_t)key[4 * i] << 24) |
               ((uint32_t)key[4 * i + 1] << 16) |
               ((uint32_t)key[4 * i + 2] << 8) |
               (uint32_t)key[4 * i + 3];
    }
    for (i = 8; i < AES256_RK_WORDS; i++) {
        uint32_t t = w[i - 1];
        if ((i & 7) == 0) {
            t = (t << 8) | (t >> 24);          /* RotWord */
            t = aes_subword(t);
            t ^= (uint32_t)rcon[i >> 3] << 24;
        } else if ((i & 7) == 4) {
            t = aes_subword(t);                /* extra SubWord for AES-256 */
        }
        w[i] = w[i - 8] ^ t;
    }
    for (i = 0; i < AES256_RK_WORDS; i++) {
        rk[4 * i]     = (uint8_t)(w[i] >> 24);
        rk[4 * i + 1] = (uint8_t)(w[i] >> 16);
        rk[4 * i + 2] = (uint8_t)(w[i] >> 8);
        rk[4 * i + 3] = (uint8_t)(w[i]);
    }
}

static void aes_add_round_key(uint8_t s[AES_BLOCK_SZ], const uint8_t *rk)
{
    int i;
    for (i = 0; i < AES_BLOCK_SZ; i++)
        s[i] = (uint8_t)(s[i] ^ rk[i]);
}

static void aes_inv_sub_bytes(uint8_t s[AES_BLOCK_SZ])
{
    int i;
    for (i = 0; i < AES_BLOCK_SZ; i++)
        s[i] = kAesInvSbox[s[i]];
}

/* Byte layout: s[r + 4*c] = state row r, column c (FIPS 197 input order). */
static void aes_inv_shift_rows(uint8_t s[AES_BLOCK_SZ])
{
    uint8_t t;

    /* row 1: rotate right by 1 */
    t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
    /* row 2: rotate right by 2 */
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    /* row 3: rotate right by 3 == left by 1 */
    t = s[3]; s[3] = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = t;
}

static void aes_inv_mix_columns(uint8_t s[AES_BLOCK_SZ])
{
    int c;
    for (c = 0; c < 4; c++) {
        uint8_t *col = &s[4 * c];
        uint8_t a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];
        col[0] = (uint8_t)(aes_gmul(a0, 14) ^ aes_gmul(a1, 11) ^
                           aes_gmul(a2, 13) ^ aes_gmul(a3, 9));
        col[1] = (uint8_t)(aes_gmul(a0, 9)  ^ aes_gmul(a1, 14) ^
                           aes_gmul(a2, 11) ^ aes_gmul(a3, 13));
        col[2] = (uint8_t)(aes_gmul(a0, 13) ^ aes_gmul(a1, 9)  ^
                           aes_gmul(a2, 14) ^ aes_gmul(a3, 11));
        col[3] = (uint8_t)(aes_gmul(a0, 11) ^ aes_gmul(a1, 13) ^
                           aes_gmul(a2, 9)  ^ aes_gmul(a3, 14));
    }
}

/* Decrypt one 16-byte block (ECB). */
static inline void aes256_ecb_decrypt_block(const uint8_t rk[AES256_RK_BYTES],
                                            const uint8_t in[AES_BLOCK_SZ],
                                            uint8_t out[AES_BLOCK_SZ])
{
    uint8_t s[AES_BLOCK_SZ];
    int round;

    memcpy(s, in, AES_BLOCK_SZ);
    aes_add_round_key(s, rk + 16 * AES256_ROUNDS);
    for (round = AES256_ROUNDS - 1; round >= 1; round--) {
        aes_inv_shift_rows(s);
        aes_inv_sub_bytes(s);
        aes_add_round_key(s, rk + 16 * round);
        aes_inv_mix_columns(s);
    }
    aes_inv_shift_rows(s);
    aes_inv_sub_bytes(s);
    aes_add_round_key(s, rk); /* round 0 */
    memcpy(out, s, AES_BLOCK_SZ);
}

/* iv = AES_ECB_DEC(key, old) XOR desired  -- the CBC patch IV. */
static inline void aes256_compute_iv(const uint8_t rk[AES256_RK_BYTES],
                                     const uint8_t old_blk[AES_BLOCK_SZ],
                                     const uint8_t desired[AES_BLOCK_SZ],
                                     uint8_t iv_out[AES_BLOCK_SZ])
{
    uint8_t dec[AES_BLOCK_SZ];
    int i;

    aes256_ecb_decrypt_block(rk, old_blk, dec);
    for (i = 0; i < AES_BLOCK_SZ; i++)
        iv_out[i] = (uint8_t)(dec[i] ^ desired[i]);
}

